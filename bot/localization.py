def get_language(context: ContextTypes.DEFAULT_TYPE) -> str:
    """Resolve the user's saved language, defaulting to Amharic."""
    user_data = getattr(context, "user_data", {}) or {}
    user = user_data.get("user", {})
    language = user.get("language") or user_data.get("language")
    return language if language in SUPPORTED_LANGUAGES else DEFAULT_LANGUAGE


def translate(language: str, key: str, **values: object) -> str:
    """Return a translated customer-facing message with safe Amharic fallback."""
    language = language if language in SUPPORTED_LANGUAGES else DEFAULT_LANGUAGE
    message = _MESSAGES.get(language, {}).get(key)
    if message is None:
        message = _MESSAGES[DEFAULT_LANGUAGE].get(key, key)
    return message.format(**values) if values else message


def get_web_login_translations(language: str) -> dict[str, str]:
    """Return login-page strings from the shared translation catalogs."""
    return {key: translate(language, f"web_login_{key}") for key in WEB_LOGIN_TRANSLATION_KEYS}


def get_web_profile_translations(language: str) -> dict[str, str]:
    """Translate legacy profile-page copy and its shared navigation shell."""
    return {source: translate(language, key) for source, key in _WEB_PROFILE_SOURCE_KEYS.items()}


def get_web_commerce_translations(language: str) -> dict[str, str]:
    """Return localized copy for web commerce features."""
    return {
        key: translate(language, f"web_commerce_{key}")
        for key in _WEB_COMMERCE_ENTRIES
    }


def tr(context: ContextTypes.DEFAULT_TYPE, key: str, **values: object) -> str:
    """Translate a key using a Telegram context's current language."""
    return translate(get_language(context), key, **values)


